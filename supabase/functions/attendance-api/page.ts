// ── 1000줄의 벽 ────────────────────────────────────────────────────────────────────
// PostgREST는 **모든 응답을 프로젝트의 max-rows(여기서는 Supabase 기본값 1000줄)에서
// 자른다.** 잘린 페이지는 온전한 페이지와 구별되지 않는다 — 오류도, 표시도 없이 그냥 줄이
// 없다. `attendance_log`가 2026년 8월에 그 선을 넘었고, 그 순간부터 `/api/roster`는 주일을
// 통째로 잃기 시작했다: 8/16은 69줄 전부가, 8/23은 82줄 중 79줄이 응답에 실리지 않아
// **출석부와 통계에서 그 주일이 비어 버렸다.** 오늘 탭만 멀쩡했던 것은 그 화면이 하루치를
// 날짜로 물어보기 때문이다 (그래서 그날 만든 출석부 이미지에는 35명·47명이 그대로 있었다).
// 자라기를 멈추지 않는 표(attendance_log · audit_log)를 통째로 읽는 자리는 전부 이 함수를
// 거친다: 페이지로 나눠 묻고, 덜 찬 페이지가 나오면 그것이 마지막이다.
//
// **정렬 칸 하나로는 페이지를 나눌 수 없다.** `ts`는 한 번의 일괄 등록이 같은 값을 나눠
// 가져 1903줄 중 982줄이 겹치는데, 값이 같은 줄들의 순서는 질의마다 달라도 되므로 그대로
// OFFSET을 걸면 어떤 줄은 두 페이지에 다 나오고 어떤 줄은 어느 페이지에도 안 나온다. 그래서
// 페이지를 나누는 질의에는 **유일한 칸(`id`)을 마지막 정렬 기준으로** 덧붙인다 — 부르는
// 쪽의 몫이라 여기서 걸어 줄 수는 없지만, 빠뜨리면 잘리는 대신 어긋난다.
//
// 실패는 삼키지 않고 던진다. 이 함수가 막는 것이 "조용히 없는 줄"인데 오류를 빈 배열로
// 돌려주면 같은 자리에 같은 증상이 다시 선다 — 부르는 쪽의 바깥 catch가 500으로 만든다.

// 한 번에 묻는 줄 수. **서버의 max-rows보다 크면 안 된다** — 크면 첫 페이지가 잘린 채로
// "덜 찼다"고 읽혀 거기서 멈춘다. 1000줄 미만인 표는 한 번만 묻고 끝나므로, 앱에서 제일
// 자주 도는 길(/api/roster)에 얹어도 왕복이 늘지 않는다.
export const PAGE_ROWS = 1000;

// PostgREST 질의를 **만드는 함수**를 받는다 (질의 객체 자체가 아니라): supabase-js의 빌더는
// 한 번 기다리면 끝이라 페이지마다 새로 세워야 한다.
export async function selectAll<T = unknown>(
  build: () => { range: (from: number, to: number) => PromiseLike<{ data: T[] | null; error: unknown }> },
  page: number = PAGE_ROWS,
): Promise<T[]> {
  const out: T[] = [];
  for (;;) {
    const { data, error } = await build().range(out.length, out.length + page - 1);
    if (error) throw error;
    const rows = data || [];
    out.push(...rows);
    if (rows.length < page) return out;
  }
}
