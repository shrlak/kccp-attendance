-- 종이는 덜 채운 생년월일도 받는다.
--
-- 장년부 새교우 카드의 생년월일은 년 / 월 / 일 세 칸인데, 실제로 년만 적어 오는 사람이 있다
-- ("2006"). members.birth_date는 날짜 칸이라 그런 값을 담지 못한다 — 지금까지는 셋이 다
-- 차야 저장했고, 덜 찬 값은 저장되지 않고 사라졌다.
--
-- 1월 1일로 채워 넣는 방법은 쓰지 않는다: 있지도 않은 생일이 생겨서 생일 목록에 뜨고,
-- 나중에 보는 사람은 그것이 적혀 있던 값인지 우리가 지어낸 값인지 알 수 없다.
--
-- 그래서 **적힌 그대로의 문자열**을 담을 칸을 따로 둔다. 완전한 날짜는 지금처럼
-- birth_date에 들어가고(날짜 계산은 그 칸만 본다), 덜 찬 값은 여기 남는다.
--   "2006"  ·  "2006-10"
-- 장년부 카드에만 있는 사정이므로 adult.members에만 붙인다.

ALTER TABLE adult.members ADD COLUMN IF NOT EXISTS birth_date_raw text;

COMMENT ON COLUMN adult.members.birth_date_raw IS
  '카드에 적힌 그대로의 생년월일 — 년만("2006") 또는 년-월("2006-10")처럼 날짜가 되지 못한 값. 완전한 날짜는 birth_date에 있다';
