-- Source: the 2026 여름 master attendance spreadsheet. Records each person's *예배*
-- attendance (동산모임 is intentionally excluded) for the summer program (6/7–8/2);
-- dates with data so far are 6/7, 6/14, 6/21. O = present (one row); X / 한국 귀국 /
-- 새가족 = no row. Adds the 4 members that were on the sheet but missing from the roster.
--
-- All analytics derive their date set from the log itself, so restricting the 여름동산
-- 출석률/analytics to 6/7–8/2 needs no code: every row here is a summer Sunday and there
-- are no rows outside the window.
--
-- Fully additive + idempotent (every write is guarded), so it is a safe no-op on prod
-- — where it was already applied operationally — and reproduces the data on fresh
-- preview branches. Names are matched by (name, 동산) so the two 김서현 stay distinct.

-- 1) The 4 missing members (all 청년부) + their ROSTER devices. New-family joiners
--    (황시연, 장시원) carry a 등록일자 so pre-join Sundays aren't counted against them.
INSERT INTO members (name, group_name, subgroup, registration_date, is_new_member)
SELECT v.name, v.grp, v.sub, v.reg::date, v.isnew
FROM (VALUES
  ('홍수민','청년부','건영동산', NULL,         false),
  ('안여진','청년부','중호동산', NULL,         false),
  ('황시연','청년부','윤서동산', '2026-06-14', true),
  ('장시원','청년부','윤서동산', '2026-06-21', true)
) AS v(name,grp,sub,reg,isnew)
WHERE NOT EXISTS (SELECT 1 FROM members m WHERE m.name=v.name AND m.subgroup=v.sub);

INSERT INTO devices (id, name, group_name, subgroup, member_id)
SELECT v.did, v.name, v.grp, v.sub, m.id
FROM (VALUES
  ('ROSTER-49','홍수민','청년부','건영동산'),
  ('ROSTER-50','안여진','청년부','중호동산'),
  ('ROSTER-51','황시연','청년부','윤서동산'),
  ('ROSTER-52','장시원','청년부','윤서동산')
) AS v(did,name,grp,sub)
JOIN members m ON m.name=v.name AND m.subgroup=v.sub
WHERE NOT EXISTS (SELECT 1 FROM devices d WHERE d.id=v.did);

